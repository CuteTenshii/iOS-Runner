/**
 * The Material Symbols icon drawn for each SF Symbol. Names are exact: `.fill` is removed first and chooses the
 * font's filled style, and every other part of a name changes what the symbol shows.
 * The font has every icon, and tools/build-icon-font.py checks these names against it.
 */
object SfSymbols {
    data class Icon(val ligature: String, val filled: Boolean)

    private const val FILL_SUFFIX = ".fill"

    fun icon(name: String): Icon? {
        val filled = name.endsWith(FILL_SUFFIX) || name.contains("$FILL_SUFFIX.")
        val base = name.replace(FILL_SUFFIX, "")
        return table[base]?.let { Icon(it, filled) }
    }

